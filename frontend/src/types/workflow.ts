/**
 * Workflow data model — shared contract between frontend and backend.
 * Backend Pydantic schemas mirror these types.
 *
 * `input` and `output` are NOT node types — the workflow's input comes
 * from `Workflow.run(input=...)` and the output is the last Step's
 * result. The canvas only carries the executable / tool-source nodes.
 *
 * row D : the per-node TypeScript config interfaces
 * used to live here as a hand mirror of
 * `backend/src/app/schemas/node_configs.py` (this file's lines
 * 99-330 prior to the codegen). Drift was easy. The mirror now lives
 * in `./node-configs.generated.ts`, regenerated by
 * `scripts/generate_node_configs_ts.py` and byte-pinned by
 * `scripts/check_node_configs_consistency.py`. We re-export the
 * generated types from here so existing imports
 * (`import type { AgentNodeConfig } from '../../types/workflow'`)
 * keep working unchanged.
 */

import type { GeneratedNodeType } from './workflow.generated'
import type {
  ConditionEvaluator,
  AskConfig,
  RouterSelector,
} from './node-configs.generated'

// ─────────────────────────────────────────────────────────────────
// Node types — manifest-derived (phase, )
// ─────────────────────────────────────────────────────────────────
// The literal union lives in `./workflow.generated.ts`, regenerated
// from `shared/nodes.manifest.json` by
// `scripts/generate_node_types.py`. The CI check
// `scripts/check_node_types_consistency.py` fails the build if the
// file drifts from the manifest. We re-export it as `NodeType` so
// existing imports (`import type { NodeType } from './workflow'`)
// keep working unchanged.
export type NodeType = GeneratedNodeType;

// ─────────────────────────────────────────────────────────────────
// MCP server (platform-wide, defined once and referenced by nodes)
// ─────────────────────────────────────────────────────────────────
export type McpTransport = 'stdio' | 'sse';

export interface McpServerConfig {
  id: string;
  name: string;
  transport: McpTransport;
  enabled: boolean;
  // stdio
  command?: string;
  args?: string[];
  env?: Record<string, string>;
  // sse / http
  url?: string;
  headers?: Record<string, string>;
  //  — per-user binding. NULL / undefined means a
  // system-shared row (visible to everyone, read-only via the API);
  // non-empty means the owning user's id. The Settings → MCP
  // editor uses this to disable the delete/edit affordances when
  // the row doesn't belong to the signed-in user.
  userId?: string | null;
}

// ─────────────────────────────────────────────────────────────────
// Per-node configs — codegen mirror of `node_configs.py` (D)
// ─────────────────────────────────────────────────────────────────
